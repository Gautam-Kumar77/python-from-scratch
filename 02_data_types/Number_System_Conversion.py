                          #BINARY NUMBER SYSTEM
#Binary Number to Decimal Number System
a= 0b101110
print(a, type(a))

#Binary Number to Octal number System
b = 0b1101
print(b, type(b))
print(oct(b))

#Binary Number to Hexa-Decimal Number System
c= 0b101011
print(c, type(c))
print(hex(c))

                          #OCTAL NUMBER SYSTEM
#Octal Number System to Decimal Number System
d= 0o453
print(d, type(d))

#Octal Number System to Binary Number System
e= 0o3463
print(e, type(e))
print(bin(e))

#Octal Number System to Hexa-Decimal Number System
f= 0O130
print(f, type(f))
print(hex(f))

                          #HEXA-DECIMAL NUMBER SYSTEM
#Hexa-Decimal Number System to Decimal Number System
g= 0x246ac
print(g, type(g))

#Hexa-Decimal Number System to Binary Number System
h= 0xface
print(h, type(h))
print(h)

#Hexa-Decimal Number System to Octal Number System
i= 0Xbee
print(i, type(i))
print(oct(i))


#Decimal Number System to All Number System
j= 3453834
print(bin(j))
print(oct(j))
print(hex(j))

